import { Router } from "express";
import { coverUpload, pdfUpload } from "./middleware/upload.js";
import { requireAdmin } from "./middleware/auth.js";
import { asyncHandler } from "./lib/errors.js";
import { loginAdmin } from "./controllers/auth.js";
import { serveOriginalPdf } from "./controllers/files.js";
import { bulkUploadChapters, chapterPdfPreview, chapterStatus, createManhwa, listAdminChapters, listManhwa, removeChapter, removeManhwa, retryChapter, updateChapter, updateManhwa, uploadChapter, } from "./controllers/admin.js";
import { getChapter, getChapterPages, getPublicManhwa, getReadingProgress, listPublicManhwa, listPublishedChapters, saveReadingProgress, } from "./controllers/reader.js";
export const adminRouter = Router();
adminRouter.use(requireAdmin);
adminRouter.get("/manhwa", asyncHandler(listManhwa));
adminRouter.post("/manhwa", coverUpload.single("coverImage"), asyncHandler(createManhwa));
adminRouter.put("/manhwa/:id", coverUpload.single("coverImage"), asyncHandler(updateManhwa));
adminRouter.delete("/manhwa/:id", asyncHandler(removeManhwa));
adminRouter.get("/manhwa/:id/chapters", asyncHandler(listAdminChapters));
adminRouter.post("/chapters/upload", pdfUpload.single("pdf"), asyncHandler(uploadChapter));
adminRouter.post("/chapters/bulk-upload", pdfUpload.array("pdfs", 25), asyncHandler(bulkUploadChapters));
adminRouter.get("/chapters/:id/status", asyncHandler(chapterStatus));
adminRouter.get("/chapters/:id/pdf", asyncHandler(chapterPdfPreview));
adminRouter.post("/chapters/:id/retry", asyncHandler(retryChapter));
adminRouter.patch("/chapters/:id", asyncHandler(updateChapter));
adminRouter.delete("/chapters/:id", asyncHandler(removeChapter));
// Short-lived, token-protected link used by the admin PDF preview (an <iframe> cannot send an Authorization header).
export const fileRouter = Router();
fileRouter.get("/chapters/:id/original.pdf", asyncHandler(serveOriginalPdf));
export const authRouter = Router();
authRouter.post("/admin/login", asyncHandler(loginAdmin));
export const readerRouter = Router();
readerRouter.get("/manhwa", asyncHandler(listPublicManhwa));
readerRouter.get("/manhwa/:id", asyncHandler(getPublicManhwa));
readerRouter.get("/manhwa/:id/chapters", asyncHandler(listPublishedChapters));
readerRouter.get("/chapters/:id", asyncHandler(getChapter));
readerRouter.get("/chapters/:id/pages", asyncHandler(getChapterPages));
readerRouter.get("/chapters/:id/progress", asyncHandler(getReadingProgress));
readerRouter.post("/chapters/:id/progress", asyncHandler(saveReadingProgress));
